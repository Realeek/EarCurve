class I18n:
    def __init__(self, lang: str = "zh") -> None:
        self.lang = lang if lang in STRINGS else "zh"

    def t(self, key: str, **vars: object) -> str:
        table = STRINGS.get(self.lang, STRINGS["zh"])
        text = table.get(key)
        if text is None:
            text = STRINGS["zh"].get(key, key)
        for name, value in vars.items():
            text = text.replace("{" + name + "}", str(value))
        return text

    def toggle(self) -> str:
        self.lang = "en" if self.lang == "zh" else "zh"
        return self.lang
